"""
Create the reference results for the reference test.
Main steps:
1. Take the synthetic data from the 5 cases generated by reference_cases.py.
2. Run the current version of NeuReval on them.
3. Save the results in a JSON file, converting numpy/pandas objects to lists, floats, ints, strings), so they can be stored in a JSON file and compared later.

Run this ONCE, on the code you trust (i.e. BEFORE starting a refactoring),
from the repository root:

    python tests/generate_reference_baseline.py

It writes tests/data/reference_baseline.json. Commit that file: from then on
test_reference.py checks that every change keeps the same results.

Only re-run it when you change NeuReval's results ON PURPOSE (e.g. a bug fix
that is supposed to change the numbers), and say so in the commit message.
"""
import json
import os
import platform
import sys
import warnings

import numpy as np
import sklearn

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reference_cases import CASES  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'reference_baseline.json')


def main():
    warnings.filterwarnings('ignore')
    results = {}
    for name, case in CASES.items():
        print(f'Running {name}...')
        results[name] = case()

    baseline = {'_environment': {'python': platform.python_version(),
                                 'numpy': np.__version__,
                                 'scikit-learn': sklearn.__version__,
                                 'platform': platform.platform()},
                **results}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        json.dump(baseline, f, indent=1)
    print(f'Saved {OUT}')


if __name__ == '__main__':
    main()
